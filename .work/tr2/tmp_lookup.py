# -*- coding: utf-8 -*-
import json, glob, os

pairs = {}
for inf in sorted(glob.glob('.work/tr2/in/batch_0*.jsonl')):
    base = os.path.basename(inf)[:-6]
    outf = f'.work/tr2/out/{base}.jsonl'
    if not os.path.exists(outf):
        continue
    srcs = {}
    for line in open(inf, encoding='utf-8'):
        line = line.strip()
        if not line:
            continue
        try:
            r = json.loads(line)
        except Exception:
            continue
        srcs[r['id']] = r['source']
    for line in open(outf, encoding='utf-8'):
        line = line.strip()
        if not line:
            continue
        try:
            r = json.loads(line)
        except Exception:
            continue
        s = srcs.get(r['id'])
        if s and s not in pairs:
            pairs[s] = r['english']
print('pairs:', len(pairs))

