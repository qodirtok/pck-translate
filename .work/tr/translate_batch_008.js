// Read input
const inputContent = fs.readFileSync(inPath, 'utf8');
const inputLines = inputContent.split(/\r?\n/).filter(l => l.trim());
const records = inputLines.map(line => JSON.parse(line));

// Translate each record
const outputRecords = records.map(rec => {
  const src = rec.source;
  let eng;
  
  if (specific.has(src)) {
    eng = specific.get(src);
  } else if (priorMap.has(src)) {
    eng = priorMap.get(src);
  } else if (glossaryMap.has(src)) {
    eng = glossaryMap.get(src);
  } else if (common.has(src)) {
    eng = common.get(src);
  } else {
    eng = applyPatterns(src);
    if (!eng) {
      // Try partial match with common map
      let partial = src;
      for (const [k, v] of common) {
        if (partial.includes(k)) {
          partial = partial.split(k).join(v);
        }
      }
      eng = partial;
    }
  }
  
  // Preserve <CRLF>, <LF>, <CR> token counts
  const srcCRLF = (src.match(/<CRLF>/g) || []).length;
  const engCRLF = (eng.match(/<CRLF>/g) || []).length;
  if (srcCRLF > engCRLF) {
    eng = eng + '<CRLF>'.repeat(srcCRLF - engCRLF);
  } else if (engCRLF > srcCRLF) {
    while ((eng.match(/<CRLF>/g) || []).length > srcCRLF) {
      eng = eng.replace(/<CRLF>/, '');
    }
  }
  
  return { id: rec.id, english: eng };
});

// Write output
const outputLines = outputRecords.map(r => JSON.stringify(r));
fs.writeFileSync(outPath, outputLines.join('\n') + '\n', 'utf8');

console.log(`Translated ${outputRecords.length} records to ${outPath}`);

// Validation
const outputContent = fs.readFileSync(outPath, 'utf8');
const outputLinesCheck = outputContent.split(/\r?\n/).filter(l => l.trim());
console.log(`Output lines: ${outputLinesCheck.length}`);
console.log(`Input lines: ${inputLines.length}`);

// Check for Chinese characters remaining
let chineseCount = 0;
for (const line of outputLinesCheck) {
  try {
    const obj = JSON.parse(line);
    if (/[\u4e00-\u9fff]/.test(obj.english)) {
      chineseCount++;
      if (chineseCount <= 5) {
        console.log(`Chinese remaining in id ${obj.id}: ${obj.english.substring(0, 80)}`);
      }
    }
  } catch (e) {}
}
console.log(`Records with Chinese remaining: ${chineseCount}`);
