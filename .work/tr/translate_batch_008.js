// Load existing translations from other batches
const outDir = '/Users/zlns/personal-www/pck-translate/.work/tr/out';
const priorMap = new Map();
try {
  const files = fs.readdirSync(outDir).filter(f => f.endsWith('.jsonl') && f !== 'batch_008.jsonl');
  for (const f of files) {
    const content = fs.readFileSync(path.join(outDir, f), 'utf8');
    const lines = content.split(/\r?\n/).filter(l => l.trim());
    for (const line of lines) {
      try {
        const obj = JSON.parse(line);
        if (obj.source && obj.english) priorMap.set(obj.source, obj.english);
      } catch (e) {}
    }
  }
} catch (e) {}

// Load glossary
const glossaryMap = new Map();
try {
  const glossaryPath = '/Users/zlns/personal-www/pck-translate/memory/glossary.db';
  const result = execSync(`sqlite3 "${glossaryPath}" "SELECT source||'\\t'||english FROM terms;"`, {encoding: 'utf8'});
  const lines = result.split(/\r?\n/).filter(l => l.trim());
  for (const line of lines) {
    const idx = line.indexOf('\t');
    if (idx > 0) {
      const src = line.slice(0, idx);
      const eng = line.slice(idx + 1);
      if (!glossaryMap.has(src)) glossaryMap.set(src, eng);
    }
  }
} catch (e) {}

